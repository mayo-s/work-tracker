"""The storage interfaces, the same for every backend (SQLite now, DynamoDB later; SPEC 7.2).

Resources and reports open a transaction on a `Storage` and get the repositories from its `Store`; they never use a
backend directly. A repository of personal records is bound to one user's id.
"""

import datetime as dt
from collections.abc import Callable, Iterable, Sequence
from contextlib import AbstractContextManager
from typing import Literal, NamedTuple, Protocol

from pydantic import JsonValue

from src.lib.balances import DayRecord, PtoTerms
from src.lib.schedules import Schedules
from src.models.base import DomainModel
from src.models.catalog import ActivityType, Service, ServiceChoice, Ticket
from src.models.days import Day
from src.models.entries import Entry
from src.models.history import EntryChange, HistoryAction
from src.models.pto import PtoYear
from src.models.review import FlagReason, ReviewFlag
from src.models.schedules import Schedule
from src.models.settings import Settings
from src.models.audit import AuditEntry
from src.models.teams import Invitation, Member, Membership, ReportView, Team, TeamRole
from src.models.users import Role, User

Clock = Callable[[], dt.datetime]
Theme = Literal['system', 'light', 'dark']
Changes = dict[str, tuple[JsonValue, JsonValue]]


class RenameResult(NamedTuple):
    ticket: Ticket
    action: HistoryAction  # renamed, or merged into an existing ticket
    moved: int  # number of entries moved


class Days(Protocol):
    def get(self, date: dt.date) -> Day | None: ...
    def between(self, start: dt.date, end: dt.date) -> list[Day]: ...
    def records(self, start: dt.date, end: dt.date) -> dict[dt.date, DayRecord]: ...
    def save(self, day: Day) -> None: ...
    def delete(self, date: dt.date) -> None: ...
    def add_flag(self, date: dt.date, reason: FlagReason, detail: str = '') -> ReviewFlag: ...
    def flags_on(self, date: dt.date) -> list[ReviewFlag]: ...
    def day_flags(self) -> list[ReviewFlag]: ...
    def clear_flag(self, flag_id: str) -> None: ...


class Entries(Protocol):
    def get(self, entry_id: str) -> Entry: ...
    def between(self, start: dt.date, end: dt.date) -> list[Entry]: ...
    def imported_together(self, entry_id: str) -> list[Entry]: ...
    def for_review(self) -> list[Entry]: ...
    def create(self, entry: Entry, action: HistoryAction = HistoryAction.CREATED, detail: str = '') -> Entry: ...
    def update(self, entry: Entry, action: HistoryAction = HistoryAction.UPDATED, detail: str = '') -> Entry: ...
    def split(self, entry_id: str, ticket_keys: Sequence[str]) -> list[Entry]: ...
    def delete(self, entry_id: str) -> None: ...
    def restore(self, entry: Entry) -> Entry: ...
    def reserve_id(self) -> str: ...
    def restore_history(self, change: EntryChange) -> EntryChange: ...
    def add_history(self, entry_id: str, action: HistoryAction, changes: Changes, detail: str = '') -> EntryChange: ...
    def history(self, entry_id: str) -> list[EntryChange]: ...
    def all_history(self) -> list[EntryChange]: ...
    def changed(self, entry_ids: Iterable[str]) -> set[str]: ...
    def add_flag(self, entry_id: str, reason: FlagReason, detail: str = '') -> ReviewFlag: ...
    def flags_of(self, entry_id: str) -> list[ReviewFlag]: ...
    def entry_flags(self) -> list[ReviewFlag]: ...
    def clear_flag(self, flag_id: str) -> None: ...
    def check_fits_day(self, entry: Entry) -> None: ...


class Tickets(Protocol):
    def get(self, key: str) -> Ticket | None: ...
    def all(self) -> list[Ticket]: ...
    def without_service(self) -> list[Ticket]: ...
    def entry_counts(self) -> dict[str, int]: ...
    def ensure(self, key: str) -> Ticket: ...
    def set_service(self, key: str, service_id: str | None) -> Ticket: ...
    def assign_service(self, keys: Iterable[str], service_id: str | None) -> int: ...


class Catalog[M: DomainModel](Protocol):
    """A managed list of one owner: a user's services or activity types, or a team's services."""

    def all(self) -> list[M]: ...
    def get(self, item_id: str) -> M: ...
    def add(self, item: M) -> M: ...
    def update(self, item: M) -> M: ...
    def delete(self, item_id: str) -> None: ...


class Services(Catalog[Service], Protocol):
    def choices(self) -> list[ServiceChoice]: ...


class WorkSchedules(Protocol):
    def all(self) -> list[Schedule]: ...
    def get(self, schedule_id: str) -> Schedule: ...
    def add(self, schedule: Schedule) -> Schedule: ...
    def update(self, schedule: Schedule) -> Schedule: ...
    def delete(self, schedule_id: str) -> None: ...
    def replace_all(self, schedule: Schedule) -> Schedule: ...
    def schedules(self) -> Schedules: ...


class PtoYears(Protocol):
    def all(self) -> list[PtoYear]: ...
    def get(self, year: int) -> PtoYear: ...
    def save(self, pto_year: PtoYear) -> PtoYear: ...
    def delete(self, year: int) -> None: ...
    def replace_all(self, pto_years: list[PtoYear]) -> None: ...
    def terms(self) -> dict[int, PtoTerms]: ...


class Users(Protocol):
    def count(self) -> int: ...
    def get(self, user_id: str) -> User: ...
    def add(self, user: User, password: str) -> User: ...
    def all(self) -> list[User]: ...
    def set_role(self, user_id: str, role: Role) -> User: ...
    def set_active(self, user_id: str, active: bool) -> User: ...
    def first_id(self) -> str | None: ...
    def root_id(self) -> str | None: ...
    def update(self, user: User) -> User: ...
    def by_login(self, login: str) -> User | None: ...
    def check_password(self, user_id: str, password: str) -> bool: ...
    def set_password(self, user_id: str, password: str) -> None: ...
    def set_one_time_password(self, user_id: str, password: str) -> None: ...


class Sessions(Protocol):
    def start(self, user_id: str, now: dt.datetime) -> str: ...
    def user_id(self, token: str, now: dt.datetime) -> tuple[str | None, bool]: ...
    def end(self, token: str) -> None: ...
    def end_expired(self, now: dt.datetime) -> None: ...


class Attempts(Protocol):
    """Failed logins and registrations, which pause both."""

    def paused(self, now: dt.datetime) -> bool: ...
    def add(self, now: dt.datetime, kind: str = 'failed_login') -> None: ...
    def clear_failed(self, now: dt.datetime) -> None: ...


class Teams(Protocol):
    def all(self) -> list[Team]: ...
    def get(self, team_id: str) -> Team: ...
    def add(self, team: Team) -> Team: ...
    def rename(self, team: Team) -> Team: ...
    def delete(self, team_id: str) -> None: ...
    def members(self, team_id: str) -> list[Member]: ...
    def membership(self, user_id: str) -> Membership | None: ...
    def history(self, user_id: str) -> list[Membership]: ...
    def join(self, user_id: str, team_id: str) -> Membership: ...
    def leave(self, user_id: str) -> None: ...
    def set_team_role(self, user_id: str, team_role: TeamRole) -> Membership: ...


class Invitations(Protocol):
    def invite(self, team_id: str, email: str, invited_by: str) -> None: ...
    def of_team(self, team_id: str) -> list[Invitation]: ...
    def withdraw(self, team_id: str, invitation_id: str) -> None: ...
    def of_user(self, user_id: str) -> list[Invitation]: ...
    def accept(self, user_id: str, invitation_id: str, teams: Teams) -> Membership: ...
    def decline(self, user_id: str, invitation_id: str) -> None: ...


class AuditLog(Protocol):
    def add(self, entry: AuditEntry) -> None: ...
    def latest(self, limit: int = 200) -> list[AuditEntry]: ...
    def of_user(self, user_id: str, limit: int = 50) -> list[AuditEntry]: ...


class ReportViews(Protocol):
    def add(self, view: ReportView) -> None: ...
    def of_member(self, member_id: str, limit: int = 50) -> list[ReportView]: ...


class Store(Protocol):
    """The repositories and settings within one transaction."""

    def days(self, user_id: str) -> Days: ...
    def entries(self, user_id: str, clock: Clock | None = None) -> Entries: ...
    def tickets(self, user_id: str) -> Tickets: ...
    def services(self, user_id: str) -> Services: ...
    def team_services(self, team_id: str) -> Services: ...
    def activity_types(self, user_id: str) -> Catalog[ActivityType]: ...
    def schedules(self, user_id: str) -> WorkSchedules: ...
    def pto_years(self, user_id: str) -> PtoYears: ...
    def users(self, clock: Clock | None = None) -> Users: ...
    def sessions(self) -> Sessions: ...
    def attempts(self) -> Attempts: ...
    def teams(self, clock: Clock | None = None) -> Teams: ...
    def invitations(self, clock: Clock | None = None) -> Invitations: ...
    def report_views(self) -> ReportViews: ...
    def audit_log(self) -> AuditLog: ...
    def rename_ticket(self, user_id: str, old_key: str, new_key: str, clock: Clock | None = None) -> RenameResult: ...
    def load_settings(self, user_id: str) -> Settings: ...
    def save_settings(self, user_id: str, settings: Settings) -> None: ...
    def setup_done(self, user_id: str) -> bool: ...
    def finish_setup(self, user_id: str) -> None: ...
    def start_import(self, user_id: str) -> None: ...
    def import_unfinished(self, user_id: str) -> bool: ...
    def clear_records(self, user_id: str) -> None: ...
    def make_room(self, items: int) -> None: ...
    def load_theme(self, user_id: str) -> Theme: ...
    def save_theme(self, user_id: str, theme: Theme) -> None: ...
    def registration_open(self) -> bool: ...
    def set_registration(self, enabled: bool) -> None: ...


